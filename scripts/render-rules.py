#!/usr/bin/env python3
"""Wrap prometheus/rules/*.rules.yaml into a PrometheusRule custom resource.

The plain rule file stays the source of truth (so promtool can test it);
CI fails if k8s/monitoring/prometheus-rules.yaml is out of date.

    python3 scripts/render-rules.py            # write the manifest
    python3 scripts/render-rules.py --check    # exit 1 if it is stale
"""

import pathlib
import sys

import yaml

ROOT = pathlib.Path(__file__).resolve().parent.parent
SOURCES = sorted((ROOT / "prometheus" / "rules").glob("*.rules.yaml"))
TARGET = ROOT / "k8s" / "monitoring" / "prometheus-rules.yaml"

HEADER = "# GENERATED by scripts/render-rules.py from prometheus/rules/ - do not edit by hand.\n"


def render() -> str:
    docs = []
    for src in SOURCES:
        groups = yaml.safe_load(src.read_text())["groups"]
        docs.append(
            {
                "apiVersion": "monitoring.coreos.com/v1",
                "kind": "PrometheusRule",
                "metadata": {
                    "name": src.name.removesuffix(".rules.yaml"),
                    "namespace": "monitoring",
                    "labels": {"app.kubernetes.io/part-of": "k8s-observability-stack"},
                },
                "spec": {"groups": groups},
            }
        )
    body = yaml.safe_dump_all(docs, sort_keys=False, width=1000, allow_unicode=True)
    return HEADER + body


def main() -> int:
    rendered = render()
    if "--check" in sys.argv:
        current = TARGET.read_text() if TARGET.exists() else ""
        if current != rendered:
            print(f"{TARGET.relative_to(ROOT)} is out of date - run: python3 scripts/render-rules.py")
            return 1
        print("PrometheusRule manifest is up to date")
        return 0
    TARGET.write_text(rendered)
    print(f"wrote {TARGET.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
